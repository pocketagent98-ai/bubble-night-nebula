package pt.tiago.bubblenight.game

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioFocusRequest
import android.media.AudioManager
import android.media.SoundPool
import android.os.Build
import android.os.SystemClock
import android.os.VibrationEffect
import android.os.Vibrator
import android.os.VibratorManager
import pt.tiago.bubblenight.R

/**
 * Local sound cues, independent from the deterministic game state.
 *
 * The cue set was widened for the Nebula layer: every booster, the daily
 * reward and the combo chain now have their own voice. Matching bubbles no
 * longer replays one sample — it walks a five-step rising ladder, so a long
 * chain reads as a melody instead of a stutter. All samples are generated by
 * `tools/gen_audio.py`, so the APK still ships no third-party audio.
 */
class AudioController(context: Context) {

    enum class Cue {
        LAUNCH, BOUNCE, MATCH, DROP, VICTORY, DEFEAT,
        BOOSTER, COIN, DAILY, STAR, LEVELUP,
        ROCKET, BOMB, FIREBALL, FREEZE, LIGHTNING, RAINBOW, SHIELD,
        UI_TAP, WHOOSH,
    }

    private val manager = context.getSystemService(AudioManager::class.java)
    private val attributes = AudioAttributes.Builder()
        .setUsage(AudioAttributes.USAGE_GAME).setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION).build()
    private val pool = SoundPool.Builder().setMaxStreams(8).setAudioAttributes(attributes).build()
    private val loaded = java.util.concurrent.ConcurrentHashMap.newKeySet<Int>()
    private val streams = ArrayDeque<Int>()
    private var active = true
    private var released = false
    private val focus = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_MAY_DUCK)
        .setAudioAttributes(attributes)
        .setOnAudioFocusChangeListener { change -> if (change < 0) stop() }.build()
    private val vibrator: Vibrator? = if (Build.VERSION.SDK_INT >= 31) {
        context.getSystemService(VibratorManager::class.java)?.defaultVibrator
    } else context.getSystemService(Vibrator::class.java)
    private val sounds: Map<Cue, Int>

    /** Rising pop ladder used by [Cue.MATCH]; the chain resets after a pause. */
    private val pops: IntArray
    private val chainStings: IntArray

    /** How many matches have landed in quick succession, 0-based, capped at 4. */
    private var chain = 0
    private var lastMatchAt = 0L

    init {
        pool.setOnLoadCompleteListener { _, id, status -> if (status == 0) loaded.add(id) }
        sounds = mapOf(
            Cue.LAUNCH to pool.load(context, R.raw.launch, 1),
            Cue.BOUNCE to pool.load(context, R.raw.bounce, 1),
            Cue.MATCH to pool.load(context, R.raw.pop1, 1),
            Cue.DROP to pool.load(context, R.raw.drop, 1),
            Cue.VICTORY to pool.load(context, R.raw.victory, 1),
            Cue.DEFEAT to pool.load(context, R.raw.defeat, 1),
            Cue.BOOSTER to pool.load(context, R.raw.booster, 1),
            Cue.COIN to pool.load(context, R.raw.coin, 1),
            Cue.DAILY to pool.load(context, R.raw.daily, 1),
            Cue.STAR to pool.load(context, R.raw.star, 1),
            Cue.LEVELUP to pool.load(context, R.raw.levelup, 1),
            Cue.ROCKET to pool.load(context, R.raw.rocket, 1),
            Cue.BOMB to pool.load(context, R.raw.bomb, 1),
            Cue.FIREBALL to pool.load(context, R.raw.fireball, 1),
            Cue.FREEZE to pool.load(context, R.raw.freeze, 1),
            Cue.LIGHTNING to pool.load(context, R.raw.lightning, 1),
            Cue.RAINBOW to pool.load(context, R.raw.rainbow, 1),
            Cue.SHIELD to pool.load(context, R.raw.shield, 1),
            Cue.UI_TAP to pool.load(context, R.raw.ui_tap, 1),
            Cue.WHOOSH to pool.load(context, R.raw.whoosh, 1),
        )
        pops = intArrayOf(
            pool.load(context, R.raw.pop1, 1),
            pool.load(context, R.raw.pop2, 1),
            pool.load(context, R.raw.pop3, 1),
            pool.load(context, R.raw.pop4, 1),
            pool.load(context, R.raw.pop5, 1),
        )
        chainStings = intArrayOf(
            pool.load(context, R.raw.chain1, 1),
            pool.load(context, R.raw.chain2, 1),
            pool.load(context, R.raw.chain3, 1),
        )
    }

    fun play(cue: Cue, sound: Boolean, haptics: Boolean) {
        if (!active || released) return
        if (sound) {
            if (cue == Cue.MATCH) {
                playMatchLadder()
            } else {
                val id = sounds.getValue(cue)
                playSample(id, volumeFor(cue), rate = 1f)
            }
        }
        if (haptics && cue in HAPTIC_CUES) {
            vibrator?.vibrate(
                VibrationEffect.createOneShot(if (cue == Cue.VICTORY) 28L else 12L, 60),
            )
        }
    }

    /**
     * Plays the next rung of the pop ladder. A gap of more than 700 ms counts as
     * a new chain, which is what keeps ordinary single pops quiet.
     */
    private fun playMatchLadder() {
        val now = SystemClock.elapsedRealtime()
        chain = if (now - lastMatchAt > CHAIN_WINDOW_MS) 0 else (chain + 1).coerceAtMost(4)
        lastMatchAt = now
        playSample(pops[chain], 0.45f, rate = 1f)
        if (chain >= 2) {
            playSample(chainStings[(chain - 2).coerceAtMost(2)], 0.30f, rate = 1f)
        }
    }

    private fun playSample(id: Int, volume: Float, rate: Float) {
        if (id !in loaded) return
        if (manager.requestAudioFocus(focus) != AudioManager.AUDIOFOCUS_REQUEST_GRANTED) return
        if (streams.size >= 8) pool.stop(streams.removeFirst())
        streams.add(pool.play(id, volume, volume, 1, 0, rate))
    }

    private fun volumeFor(cue: Cue): Float = when (cue) {
        Cue.UI_TAP -> 0.28f
        Cue.BOUNCE -> 0.32f
        Cue.DAILY, Cue.LEVELUP -> 0.60f
        Cue.BOMB, Cue.LIGHTNING, Cue.FIREBALL -> 0.50f
        else -> 0.45f
    }

    fun setActive(value: Boolean) {
        active = value
        if (!value) stop()
    }

    fun stop() {
        if (released) return
        streams.forEach(pool::stop)
        streams.clear()
        vibrator?.cancel()
        manager.abandonAudioFocusRequest(focus)
    }

    fun release() {
        if (released) return
        stop()
        pool.release()
        released = true
    }

    private companion object {
        const val CHAIN_WINDOW_MS = 700L
        val HAPTIC_CUES = setOf(Cue.MATCH, Cue.DROP, Cue.VICTORY, Cue.BOMB, Cue.LEVELUP)
    }
}
