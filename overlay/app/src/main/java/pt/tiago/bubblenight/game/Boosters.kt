            "Adds three shots to the budget for the rest of the level.",
        ),
    )

    /** Booster ids unlocked at a given campaign orbit and daily streak. */
    fun unlockedAt(orbit: Int, streak: Int): Set<BoosterId> =
        all.filter { isUnlocked(it.unlock, orbit, streak) }.map { it.id }.toSet()

    fun isUnlocked(unlock: BoosterUnlock, orbit: Int, streak: Int): Boolean = when (unlock) {
        BoosterUnlock.STARTER -> true
        BoosterUnlock.ORBIT_2 -> orbit >= 2
        BoosterUnlock.ORBIT_4 -> orbit >= 4
        BoosterUnlock.ORBIT_6 -> orbit >= 6
        BoosterUnlock.ORBIT_9 -> orbit >= 9
        BoosterUnlock.STREAK_3 -> streak >= 3
        BoosterUnlock.STREAK_7 -> streak >= 7
    }

    fun byId(id: BoosterId): BoosterSpec = all.first { it.id == id }

    /**
     * True when the booster may fire again. [shotsSinceUse] counts shots taken
     * since its last activation; a value at or above the cooldown re-arms it.
     */
    fun isReady(spec: BoosterSpec, shotsSinceUse: Int): Boolean = shotsSinceUse >= spec.cooldownShots

    /** Fraction 0..1 of the cooldown already elapsed, for the radial tray indicator. */
    fun cooldownFraction(spec: BoosterSpec, shotsSinceUse: Int): Float {
        if (spec.cooldownShots <= 0) return 1f
        return (shotsSinceUse.toFloat() / spec.cooldownShots.toFloat()).coerceIn(0f, 1f)
    }
}
