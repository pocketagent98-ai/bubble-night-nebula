package pt.tiago.bubblenight.game

/**
 * The booster catalogue.
 *
 * The three reference games all gate their best moments behind a booster, so
 * this layer keeps every booster a *rule* rather than a shop item: each one has
 * a deterministic effect, a cooldown in shots and an unlock condition that the
 * campaign already knows about (orbit reached, daily streak). Nothing here is
 * purchasable, which keeps the game offline and ad-free.
 */

enum class BoosterId {
    FIREBALL, BOMB, ROCKET, LIGHTNING, FREEZE, SHIELD, RAINBOW, MAGNET, SHUFFLE, TIMEWARP,
}

/** When a booster becomes available. Ordered: later values unlock later. */
enum class BoosterUnlock {
    STARTER, ORBIT_2, ORBIT_4, ORBIT_6, ORBIT_9, STREAK_3, STREAK_7,
}

/**
 * One booster.
 *
 * @param sound raw-resource name of its cue, generated by `tools/gen_audio.py`.
 * @param cooldownShots how many shots must pass before it can be armed again.
 * @param clearsRadius board cells cleared around the impact, 0 for board-wide.
 */
data class BoosterSpec(
    val id: BoosterId,
    val label: String,
    val glyph: String,
    val sound: String,
    val cooldownShots: Int,
    val unlock: BoosterUnlock,
    val clearsRadius: Int,
    val description: String,
)

object Boosters {

    val all: List<BoosterSpec> = listOf(
